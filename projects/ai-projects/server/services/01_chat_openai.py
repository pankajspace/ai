"""OpenAI Chat Completion Service - Travel Guide.

This service demonstrates direct LLM chat completion using the official OpenAI API:
1. Loads API credentials and model configuration from environment variables (.env).
2. Uses Pydantic models (TravelRequest, TravelResponse) for type validation and HTTP serialization.
3. Formats system and user prompts to guide the LLM's persona and task.
4. Executes the OpenAI Chat Completion endpoint with a 15-second safety timeout.

Run directly:
    python projects/ai-projects/server/services/01_chat_openai.py
"""

import os
from dotenv import find_dotenv, load_dotenv
from openai import OpenAI
from pydantic import BaseModel, Field

# ---------------------------------------------------------------------------
# Configuration & Environment Setup
# ---------------------------------------------------------------------------
# Automatically locate and load the nearest .env file (e.g. at the repo or project root)
load_dotenv(find_dotenv())


# ---------------------------------------------------------------------------
# Request & Response Schemas (Pydantic)
# ---------------------------------------------------------------------------
class TravelRequest(BaseModel):
    """Input payload for travel suggestion queries."""

    city: str = Field(
        default="Bangalore",
        description="City to get a travel suggestion for",
    )


class TravelResponse(BaseModel):
    """Output payload containing the target city and generated suggestion."""

    city: str
    suggestion: str


# ---------------------------------------------------------------------------
# Core Service Logic
# ---------------------------------------------------------------------------
def get_travel_suggestion(city: str = "Bangalore") -> str:
    """Suggest one thing to do in a given city using OpenAI.

    Args:
        city: Target city name (defaults to "Bangalore").

    Returns:
        A witty travel recommendation generated by the OpenAI model.
    """
    # ① Fetch model identifier configured in .env (defaults to gpt-4o-mini if unspecified)
    model = os.getenv("OPENAI_MODEL", "gpt-4o-mini")

    # ② Initialize the OpenAI client (reads OPENAI_API_KEY from environment)
    client = OpenAI()

    # ③ Call the Chat Completion endpoint
    # - system message: assigns the persona/tone ("witty travel guide")
    # - user message: provides the specific prompt instruction
    response = client.chat.completions.create(
        model=model,
        messages=[
            {"role": "system", "content": "You are a witty travel guide."},
            {"role": "user", "content": f"Suggest one thing to do in {city}."},
        ],
        timeout=15.0,
    )

    # ④ Extract and return the assistant's reply
    return response.choices[0].message.content or ""


# ---------------------------------------------------------------------------
# Standalone CLI Verification
# ---------------------------------------------------------------------------
if __name__ == "__main__":
    print("--- Testing OpenAI Travel Guide Service ---")
    print(get_travel_suggestion("Bangalore"))
