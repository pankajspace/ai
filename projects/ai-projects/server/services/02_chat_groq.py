"""Groq Chat Completion Service - Joke Generator.

This service demonstrates using an alternative high-speed LLM provider (Groq)
via the OpenAI-compatible client interface:
1. Groq hosts open-weights models (such as LLaMA 3.3 70B) with high inference speed.
2. The standard `openai.OpenAI` client is reused by setting `base_url` to Groq's endpoint
   and authenticating with `GROQ_API_KEY`.
3. Pydantic models (JokeRequest, JokeResponse) validate and serialize API payloads.
4. Includes defensive validation to ensure API keys are configured before calling.

Run directly:
    python projects/ai-projects/server/services/02_chat_groq.py
"""

import os
from dotenv import find_dotenv, load_dotenv
from openai import OpenAI
from pydantic import BaseModel, Field

# ---------------------------------------------------------------------------
# Configuration & Environment Setup
# ---------------------------------------------------------------------------
# Automatically locate and load the nearest .env file (e.g. at the repo or project root)
load_dotenv(find_dotenv())


# ---------------------------------------------------------------------------
# Request & Response Schemas (Pydantic)
# ---------------------------------------------------------------------------
class JokeRequest(BaseModel):
    """Input payload specifying the joke topic."""

    topic: str = Field(
        default="programming",
        description="Topic for the joke",
    )


class JokeResponse(BaseModel):
    """Output payload containing the topic and generated joke."""

    topic: str
    joke: str


# ---------------------------------------------------------------------------
# Core Service Logic
# ---------------------------------------------------------------------------
def get_groq_joke(topic: str = "programming") -> str:
    """Tell a funny joke on a topic using Groq.

    Args:
        topic: Topic for the joke (defaults to "programming").

    Returns:
        A humorous joke generated by the Groq model.

    Raises:
        ValueError: If GROQ_API_KEY is not defined in the environment.
    """
    # Verify that the Groq API key is present in environment variables
    api_key = os.getenv("GROQ_API_KEY")
    if not api_key:
        raise ValueError("GROQ_API_KEY is not configured in .env")

    # Read endpoint and model configuration (falling back to sensible defaults)
    base_url = os.getenv("GROQ_BASE_URL", "https://api.groq.com/openai/v1")
    model = os.getenv("GROQ_MODEL", "llama-3.3-70b-versatile")

    # Initialize the OpenAI SDK client configured for Groq's base URL
    client = OpenAI(
        api_key=api_key,
        base_url=base_url,
        timeout=15.0,
    )

    # Call the chat completions endpoint with system persona and user topic
    response = client.chat.completions.create(
        model=model,
        messages=[
            {"role": "system", "content": "You are a funny joke teller."},
            {"role": "user", "content": f"Tell me a joke about {topic}."},
        ],
        timeout=15.0,
    )

    # Extract and return the joke text
    return response.choices[0].message.content or ""


# ---------------------------------------------------------------------------
# Standalone CLI Verification
# ---------------------------------------------------------------------------
if __name__ == "__main__":
    print("--- Testing Groq Joke Generator Service ---")
    print(get_groq_joke("programming"))